  $("#fontSelect").addEventListener("change", (e) => { state.font = e.target.value; save(); applyPrefs(); });
  $("#smallerBtn").addEventListener("click", () => { state.sizeIndex = Math.max(0, state.sizeIndex - 1); save(); applyPrefs(); });
  $("#biggerBtn").addEventListener("click", () => { state.sizeIndex = Math.min(SIZES.length - 1, state.sizeIndex + 1); save(); applyPrefs(); });
  $("#installBtn").addEventListener("click", doInstall);
  $("#importFile").addEventListener("change", (e) => { if (e.target.files[0]) importProgress(e.target.files[0]); e.target.value = ""; });
  $("#searchInput").addEventListener("input", (e) => renderSearch(e.target.value));
  document.addEventListener("keydown", (e) => {
    if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === "k") { e.preventDefault(); openSearch(); }
    if (e.key === "Escape") { closeSearch(); closeSidebar(); }
  });
  window.addEventListener("hashchange", () => render());
  window.addEventListener("online", updateNet);
  window.addEventListener("offline", updateNet);

