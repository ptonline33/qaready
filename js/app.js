  function normText(s) { return String(s).trim().replace(/\s+/g, " "); }
  function buildInput(ctx, done) {
    const { ex, body } = ctx;
    const row = document.createElement("div"); row.className = "answer-row";
    const input = document.createElement("input");
    input.type = "text"; input.autocomplete = "off"; input.spellcheck = false;
    input.placeholder = "Type your answer…"; input.setAttribute("aria-label", "Your answer");
    const btn = document.createElement("button");
    btn.type = "button"; btn.className = "check-btn"; btn.textContent = "Check";
    row.append(input, btn); body.append(row);
    const check = () => {
      const given = normText(input.value);
      if (!given) { ctx.complete(false, "Type an answer first."); return; }
      const hit = ex.answers.some((a) => {
        const want = normText(a);
        return ex.caseSensitive ? given === want : given.toLowerCase() === want.toLowerCase();
      });
      if (hit) { input.disabled = true; ctx.complete(true, "Correct! " + (ex.explain || "")); }
      else ctx.complete(false, "Not quite. Check your answer and try again.");
    };
    btn.addEventListener("click", check);
    input.addEventListener("keydown", (e) => { if (e.key === "Enter") check(); });
    if (done) { input.disabled = true; ctx.feedback.textContent = "Already completed."; }
  }

  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
    return a;
  }
  function buildOrder(ctx, done) {
    const { ex, body } = ctx;
    const pool = document.createElement("div"); pool.className = "order-pool";
    const tray = document.createElement("div"); tray.className = "order-tray";
    const actions = document.createElement("div"); actions.className = "ex-actions";
    const reset = document.createElement("button");
    reset.type = "button"; reset.className = "btn sm ghost"; reset.textContent = "Reset";
    actions.append(reset); body.append(tray, pool, actions);
    const chosen = [];
    const renderPool = () => {
      pool.textContent = "";
      shuffle(ex.items.map((_, i) => i)).forEach((i) => {
        const b = document.createElement("button");
        b.type = "button"; b.className = "opt"; b.textContent = ex.items[i];
        b.addEventListener("click", () => {
          chosen.push(i); b.remove();
          const placed = document.createElement("span");
          placed.className = "placed"; placed.textContent = `${chosen.length}. ${ex.items[i]}`;
          tray.append(placed);
          if (chosen.length === ex.items.length) evaluate();
        });
        pool.append(b);
      });
    };
    const evaluate = () => {
      const correct = chosen.every((v, i) => v === i);
      tray.classList.add(correct ? "ok" : "bad");
      if (correct) { pool.textContent = ""; ctx.complete(true, "Correct! " + (ex.explain || "")); }
      else ctx.complete(false, "That order isn't right. Press Reset and try again.");
    };
    reset.addEventListener("click", () => {
      chosen.length = 0; tray.textContent = ""; tray.classList.remove("ok", "bad"); renderPool();
    });
    if (done) {
      ex.items.forEach((item, i) => {
        const s = document.createElement("span"); s.className = "placed"; s.textContent = `${i + 1}. ${item}`; tray.append(s);
      });
      tray.classList.add("ok"); ctx.feedback.textContent = "Already completed.";
    } else renderPool();
  }

  function buildMarkdown(ctx, done) {
    const { ex, body } = ctx;
    const ta = document.createElement("textarea");
    ta.className = "md-editor"; ta.value = done ? ex.solution : (ex.starter || "");
    ta.spellcheck = false; ta.setAttribute("aria-label", "Your document");
    const preview = document.createElement("div"); preview.className = "md-preview";
    const actions = document.createElement("div"); actions.className = "ex-actions";
    const check = document.createElement("button");
    check.type = "button"; check.className = "check-btn"; check.textContent = "Check document";
    actions.append(check); body.append(ta, preview, actions);
    const render = () => { preview.innerHTML = ta.value.trim() ? md(ta.value) : '<p class="muted">The rendered preview appears here as you type.</p>'; hydrate(preview); };
    ta.addEventListener("input", render); render();
    check.addEventListener("click", () => {
      const src = ta.value;
      if (!src.trim()) { ctx.complete(false, "Write something first."); return; }
      const missed = ex.patterns.filter((p) => !new RegExp(p.re, "im").test(src));
      if (missed.length) ctx.complete(false, "Almost — still missing: " + missed.map((p) => p.m).join("; "));
      else ctx.complete(true, "Correct! " + (ex.explain || ""));
    });
  }

  function buildSQL(ctx, done) {
    const { ex, body } = ctx;
    const schema = document.createElement("details"); schema.className = "schema-box";
    schema.innerHTML = `<summary>Database schema (click to view)</summary><div style="margin-top:8px">${ex.db.map((t) => `<div><code>${esc(t.name)}</code>( ${t.columns.map((c) => `<code>${esc(c)}</code>`).join(", ")} ) — ${t.rows.length} rows</div>`).join("")}</div>`;
    const ta = document.createElement("textarea");
    ta.className = "sql-editor"; ta.value = done ? ex.solution : "";
    ta.placeholder = "SELECT ... FROM ..."; ta.spellcheck = false; ta.setAttribute("aria-label", "SQL query");
    const actions = document.createElement("div"); actions.className = "ex-actions";
    const run = document.createElement("button"); run.type = "button"; run.className = "btn sm"; run.textContent = "Run query";
    const check = document.createElement("button"); check.type = "button"; check.className = "check-btn"; check.textContent = "Check answer";
    const sol = document.createElement("button"); sol.type = "button"; sol.className = "btn sm ghost"; sol.textContent = "Show solution";
    actions.append(run, check, sol);
    const out = document.createElement("div"); out.className = "result-wrap";
    body.append(schema, ta, actions, out);

    const expectedHint = `<p class="sql-result-msg">Expected: <strong>${ex.expected.rows.length}</strong> row(s) × <strong>${ex.expected.columns.length}</strong> column(s). Column names don't have to match exactly, but the values do.</p>`;
    out.innerHTML = expectedHint;

    const resultTable = (r) => `<table class="result-table"><thead><tr>${r.columns.map((c) => `<th>${esc(c)}</th>`).join("")}</tr></thead><tbody>${r.rows.map((row) => `<tr>${row.map((v) => `<td>${v === null || v === undefined ? "NULL" : esc(v)}</td>`).join("")}</tr>`).join("")}</tbody></table>`;
    const doRun = () => {
      try {
        const r = window.SQL.run(ex.db, ta.value);
        out.innerHTML = `<p class="sql-result-msg">${r.rows.length} row(s) returned:</p>` + resultTable(r) + expectedHint;
        return r;
      } catch (err) {
        out.innerHTML = `<p class="ex-feedback bad">${esc(err.message)}</p>` + expectedHint;
        return null;
      }
    };
    run.addEventListener("click", doRun);
    check.addEventListener("click", () => {
      const r = doRun();
      if (!r) { ctx.complete(false, "Fix the query error above first."); return; }
      const sameShape = r.columns.length === ex.expected.columns.length;
      const sameRows = JSON.stringify(r.rows) === JSON.stringify(ex.expected.rows);
      if (sameShape && sameRows) ctx.complete(true, "Correct! Your query returns the expected data. " + (ex.explain || ""));
      else if (sameShape) ctx.complete(false, "The column count is right but the values differ. Check your WHERE / JOIN / GROUP BY.");
      else ctx.complete(false, `Expected ${ex.expected.columns.length} column(s), got ${r.columns.length}.`);
    });
    sol.addEventListener("click", () => { ta.value = ex.solution; doRun(); });
    ta.addEventListener("keydown", (e) => { if ((e.ctrlKey || e.metaKey) && e.key === "Enter") { e.preventDefault(); check.click(); } });
    if (done) ctx.feedback.textContent = "Already completed — you can keep experimenting with the query.";
  }

