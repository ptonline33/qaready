  document.addEventListener("click", (e) => {
    const go = e.target.closest("[data-go]");
    if (go) { location.hash = go.getAttribute("data-go"); closeSidebar(); return; }
    const el = e.target.closest("[data-act]");
    if (!el) return;
    const a = el.dataset.act;

    switch (a) {
      case "markLesson": {
        const c = courseById[el.dataset.c], i = Number(el.dataset.i);
        const l = c.lessons[i];
        if (state.lessonDone[l.id]) { delete state.lessonDone[l.id]; save(); toast("Marked as not complete."); }
        else {
          state.lessonDone[l.id] = Date.now();
          for (let k = 0; k < exCount(c, i); k++) if (!isExDone(c.id, i, k)) setExDone(c.id, i, k);
          save(); markActive(); toast("Lesson marked complete.");
        }
        render(true); break;
      }
      case "bookmark": {
        const id = el.dataset.id, ix = state.bookmarks.indexOf(id);
        if (ix >= 0) state.bookmarks.splice(ix, 1); else state.bookmarks.push(id);
        save(); render(true); toast(ix >= 0 ? "Bookmark removed." : "Bookmarked."); break;
      }
      case "quizPick": {
        if (!ui.quiz || ui.quiz.submitted) return;
        const qi = Number(el.dataset.q), oi = Number(el.dataset.o);
        ui.quiz.questions[qi].chosen = oi;
        $$(`.quiz-q[data-q="${qi}"] .quiz-option`).forEach((b, k) => b.classList.toggle("on", k === oi));
        break;
      }
      case "quizSubmit": submitQuiz(el.dataset.id); break;
      case "courseFilter": ui.courseFilter = el.dataset.v; render(true); break;
      case "glossaryCat": ui.glossaryCat = el.dataset.v; render(true); break;
      case "toolkitTab": ui.toolkitTab = el.dataset.v; render(true); break;
      case "careerTab": ui.careerTab = el.dataset.v; render(true); break;
      case "qaCat": ui.qaCat = el.dataset.v; render(true); break;
      case "flashStart": ui.flash = { active: true, order: shuffle(D.glossary.map((_, i) => i)), idx: 0, flipped: false }; render(true); break;
      case "flashFlip": ui.flash.flipped = !ui.flash.flipped; render(true); break;
      case "flashGot": flashAdvance(true); break;
      case "flashAgain": flashAdvance(false); break;
      case "flashExit": ui.flash = null; render(true); break;
      case "flashShuffle": ui.flash.order = shuffle(D.glossary.map((_, i) => i)); ui.flash.idx = 0; ui.flash.flipped = false; render(true); break;
      case "themeSet": break; // handled by change
      case "fontSet": break;
      case "sizeUp": state.sizeIndex = Math.min(SIZES.length - 1, state.sizeIndex + 1); save(); applyPrefs(); render(true); break;
      case "sizeDown": state.sizeIndex = Math.max(0, state.sizeIndex - 1); save(); applyPrefs(); render(true); break;
      case "search": openSearch(); break;
      case "searchClose": closeSearch(); break;
      case "install": doInstall(); break;
      case "export": exportProgress(); break;
      case "import": $("#importFile").click(); break;
      case "reset":
        if (confirm("Reset ALL progress? This cannot be undone. Export a backup first if you're unsure.")) {
          const prefs = { theme: state.theme, font: state.font, sizeIndex: state.sizeIndex };
          state = Object.assign(fresh(), prefs); save(); applyPrefs(); render(true); toast("All progress reset.");
        }
        break;
      case "clearCache":
        if (navigator.serviceWorker?.controller) {
          navigator.serviceWorker.controller.postMessage({ type: "CLEAR_CACHE" });
          toast("Cache refreshed — reloading…"); setTimeout(() => location.reload(), 700);
        } else toast("Cache will refresh on the next visit.");
        break;
    }
  });

